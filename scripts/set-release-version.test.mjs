/** Deliberately older than any release, so every field has to be rewritten. */
const stale = "0.1.0";

function fixture(info) {
  const name = packageName(info);
  const optionalDependencies = Object.fromEntries(
    Object.keys(platforms).map((platform) => [`${name}-${platform}`, stale]),
  );
  const devDependencies = { "ai-hist": localCoreDependency };
  const peerDependencies = { "ai-hist": `^${stale}` };
  return {
    manifest: {
      name,
      version: stale,
      license: "MIT",
      // Real manifests must declare this or `npm publish --provenance` fails
      // E422; the contract asserts it, so the fixture carries it too.
      repository: repositoryField("plugins/fixture/sdk"),
      peerDependencies,
      devDependencies,
      optionalDependencies,
    },
    lock: {
      name,
      version: stale,
      lockfileVersion: 3,
      requires: true,
      packages: {
        "": {
          name,
          version: stale,
          devDependencies,
          optionalDependencies: { ...optionalDependencies },
          peerDependencies: { ...peerDependencies },
        },
        "../../../sdk-ts": { name: "ai-hist", version: stale, dev: true },
        "node_modules/ai-hist": { resolved: "../../../sdk-ts", link: true },
        ...Object.fromEntries(
          Object.keys(platforms).map((platform) => [
            `node_modules/${name}-${platform}`,
            { version: stale, optional: true, license: "MIT" },
          ]),
        ),
      },
    },
  };
}

/** The crate each plugin's helper (and, for relayhistory, the probe) builds
 * from. Its own Cargo workspace, so the lock beside it names it too. */
